-- 95_shap_muestra.sql | muestra estratificada por poblacion y codmes con las 39 variables del modelo casteadas a DOUBLE, sin key_value ni tip_doc, para correr TreeSHAP contra el artefacto
CREATE TABLE disc_model_owner.ds_adm_bpe_shap_muestra
WITH (
    format               = 'PARQUET',
    parquet_compression  = 'SNAPPY',
    external_location    = '<S3_DATOS>/shap_v1/'
) AS
SELECT codmes,
       pob,
       entidad,
       personeria,
       flg_ppjj,
       flg_clean,
       flg_clean_calib,
       flg_calib,
       n_estrato,
       pd_raw,
       pd_cal,
       rho_i,
       fhat,
       prob_modelo_cal,
       puntuacion_modelo,
       target_12m,
       probabilidad,
       woe_prm_decresldo12m,
       woe_max_nrocredsldo06m,
       woe_nro_decresldo12m,
       rat_promsldnegdecre03y06m,
       woe_cant_vehi,
       woe_cant_entireportsisnoreg,
       woe_dpt_grupo_v2,
       woe_edad,
       woe_avg_porcsald_otrasent12m,
       woe_prm_deudatelco12m,
       woe_anti_negmeses,
       woe_prm_decresldopp12m,
       woe_min_sldopasi06m,
       woe_beta_nroenti,
       woe_beta_sldoppcomer,
       woe_prm_decresldotc12m,
       woe_prm_porcsldoimpa12m,
       woe_prm_usotcfueraibk12m,
       woe_beta_sldotc12m,
       woe_prm_nrotrxcashout06m,
       woe_nro_dismsaldonormal12mcny,
       woe_peor_clasicony09m,
       woe_max_dismsldoretail03m,
       woe_ciiu_grupo_v2,
       woe_max_dismsldo12rl,
       woe_nro_mesesdismsldoretail12m,
       woe_max_nroentinegocny06m,
       woe_prm_ratdispefect03m,
       woe_nro_mesescastin06m,
       rat_promsldnegdecreprin3y6m,
       woe_max_dismsldonoprinc12m,
       woe_nro_mesesatrasmay8dias09m,
       woe_beta_sldopp12m,
       woe_rat_sldo09msobre12mrl,
       woe_max_diasatras09mrl,
       woe_prm_valorexpimp12m,
       woe_nro_mesesdicmsldoprinc12m,
       woe_porc_messldogiro06m,
       woe_rat_sldonormal3msobre12mrl
FROM (
    SELECT g.cm                                  AS codmes,
           g.pob                                 AS pob,
           g.ent                                 AS entidad,
           g.per                                 AS personeria,
           g.fj                                  AS flg_ppjj,
           g.fc                                  AS flg_clean,
           g.fcc                                 AS flg_clean_calib,
           g.fk                                  AS flg_calib,
           g.pdr                                 AS pd_raw,
           g.pdc                                 AS pd_cal,
           g.rho                                 AS rho_i,
           g.fht                                 AS fhat,
           g.pmc                                 AS prob_modelo_cal,
           g.pun                                 AS puntuacion_modelo,
           g.t12                                 AS target_12m,
           TRY_CAST(s.probabilidad AS DOUBLE)    AS probabilidad,
           TRY_CAST(s.woe_prm_decresldo12m AS DOUBLE)  AS woe_prm_decresldo12m,
           TRY_CAST(s.woe_max_nrocredsldo06m AS DOUBLE)  AS woe_max_nrocredsldo06m,
           TRY_CAST(s.woe_nro_decresldo12m AS DOUBLE)  AS woe_nro_decresldo12m,
           TRY_CAST(s.rat_promsldnegdecre03y06m AS DOUBLE)  AS rat_promsldnegdecre03y06m,
           TRY_CAST(s.woe_cant_vehi AS DOUBLE)  AS woe_cant_vehi,
           TRY_CAST(s.woe_cant_entireportsisnoreg AS DOUBLE)  AS woe_cant_entireportsisnoreg,
           TRY_CAST(s.woe_dpt_grupo_v2 AS DOUBLE)  AS woe_dpt_grupo_v2,
           TRY_CAST(s.woe_edad AS DOUBLE)   AS woe_edad,
           TRY_CAST(s.woe_avg_porcsald_otrasent12m AS DOUBLE)  AS woe_avg_porcsald_otrasent12m,
           TRY_CAST(s.woe_prm_deudatelco12m AS DOUBLE)  AS woe_prm_deudatelco12m,
           TRY_CAST(s.woe_anti_negmeses AS DOUBLE)  AS woe_anti_negmeses,
           TRY_CAST(s.woe_prm_decresldopp12m AS DOUBLE)  AS woe_prm_decresldopp12m,
           TRY_CAST(s.woe_min_sldopasi06m AS DOUBLE)  AS woe_min_sldopasi06m,
           TRY_CAST(s.woe_beta_nroenti AS DOUBLE)  AS woe_beta_nroenti,
           TRY_CAST(s.woe_beta_sldoppcomer AS DOUBLE)  AS woe_beta_sldoppcomer,
           TRY_CAST(s.woe_prm_decresldotc12m AS DOUBLE)  AS woe_prm_decresldotc12m,
           TRY_CAST(s.woe_prm_porcsldoimpa12m AS DOUBLE)  AS woe_prm_porcsldoimpa12m,
           TRY_CAST(s.woe_prm_usotcfueraibk12m AS DOUBLE)  AS woe_prm_usotcfueraibk12m,
           TRY_CAST(s.woe_beta_sldotc12m AS DOUBLE)  AS woe_beta_sldotc12m,
           TRY_CAST(s.woe_prm_nrotrxcashout06m AS DOUBLE)  AS woe_prm_nrotrxcashout06m,
           TRY_CAST(s.woe_nro_dismsaldonormal12mcny AS DOUBLE)  AS woe_nro_dismsaldonormal12mcny,
           TRY_CAST(s.woe_peor_clasicony09m AS DOUBLE)  AS woe_peor_clasicony09m,
           TRY_CAST(s.woe_max_dismsldoretail03m AS DOUBLE)  AS woe_max_dismsldoretail03m,
           TRY_CAST(s.woe_ciiu_grupo_v2 AS DOUBLE)  AS woe_ciiu_grupo_v2,
           TRY_CAST(s.woe_max_dismsldo12rl AS DOUBLE)  AS woe_max_dismsldo12rl,
           TRY_CAST(s.woe_nro_mesesdismsldoretail12m AS DOUBLE)  AS woe_nro_mesesdismsldoretail12m,
           TRY_CAST(s.woe_max_nroentinegocny06m AS DOUBLE)  AS woe_max_nroentinegocny06m,
           TRY_CAST(s.woe_prm_ratdispefect03m AS DOUBLE)  AS woe_prm_ratdispefect03m,
           TRY_CAST(s.woe_nro_mesescastin06m AS DOUBLE)  AS woe_nro_mesescastin06m,
           TRY_CAST(s.rat_promsldnegdecreprin3y6m AS DOUBLE)  AS rat_promsldnegdecreprin3y6m,
           TRY_CAST(s.woe_max_dismsldonoprinc12m AS DOUBLE)  AS woe_max_dismsldonoprinc12m,
           TRY_CAST(s.woe_nro_mesesatrasmay8dias09m AS DOUBLE)  AS woe_nro_mesesatrasmay8dias09m,
           TRY_CAST(s.woe_beta_sldopp12m AS DOUBLE)  AS woe_beta_sldopp12m,
           TRY_CAST(s.woe_rat_sldo09msobre12mrl AS DOUBLE)  AS woe_rat_sldo09msobre12mrl,
           TRY_CAST(s.woe_max_diasatras09mrl AS DOUBLE)  AS woe_max_diasatras09mrl,
           TRY_CAST(s.woe_prm_valorexpimp12m AS DOUBLE)  AS woe_prm_valorexpimp12m,
           TRY_CAST(s.woe_nro_mesesdicmsldoprinc12m AS DOUBLE)  AS woe_nro_mesesdicmsldoprinc12m,
           TRY_CAST(s.woe_porc_messldogiro06m AS DOUBLE)  AS woe_porc_messldogiro06m,
           TRY_CAST(s.woe_rat_sldonormal3msobre12mrl AS DOUBLE)  AS woe_rat_sldonormal3msobre12mrl,
           count(*) OVER (PARTITION BY g.pob, g.cm) AS n_estrato,
           row_number() OVER (PARTITION BY g.pob, g.cm ORDER BY xxhash64(to_utf8(CAST(s.key_value AS VARCHAR)))) AS rn
    FROM e_perm_aws.scr_admbankbpe_rsk s
    JOIN (
        SELECT CAST(tip_doc AS VARCHAR) AS td, CAST(key_value AS VARCHAR) AS kv,
               CAST(codmes AS VARCHAR) AS cm,
               CASE WHEN entidad = 'IBK' THEN 'IBK'
                    WHEN entidad = 'OTRO' THEN 'SSFF'
                    ELSE 'RESTO_TOP4' END AS pob,
               entidad AS ent, personeria AS per, flg_ppjj AS fj,
               flg_clean AS fc, flg_clean_calib AS fcc, flg_calib AS fk,
               pd_raw AS pdr, pd_cal AS pdc, rho_i AS rho, fhat AS fht,
               prob_modelo_cal AS pmc, puntuacion_modelo AS pun, target_12m AS t12
        FROM disc_model_owner.ds_adm_bpe_bankbn_cal_202607
        WHERE pd_raw IS NOT NULL
          AND codmes BETWEEN '202407' AND '202606'
    ) g
      ON g.td = CAST(s.tip_doc AS VARCHAR)
     AND g.kv = CAST(s.key_value AS VARCHAR)
     AND g.cm = CAST(DATE_FORMAT(DATE_ADD('month', 1, DATE_PARSE(CAST(s.p_codmes AS VARCHAR), '%Y%m')), '%Y%m') AS VARCHAR)
    WHERE s.p_codmes BETWEEN '202406' AND '202605'
) q
WHERE rn <= 1000
