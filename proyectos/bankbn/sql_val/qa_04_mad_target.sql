-- qa_04_mad_target.sql | familia target_01m..12m (monotonia, madurez, escalera de fronteras) mas 17 invariantes de ds_adm_bpe_bankbn_mad | REGLA UNICA: n_viol y n_viol2 tienen que ser 0 en TODAS las filas
WITH a AS (
    SELECT
        CAST(count(1) AS BIGINT) AS n_filas,
        CAST(count(DISTINCT CAST(codmes AS VARCHAR) || '#' || CAST(tip_doc AS VARCHAR) || '#' || CAST(key_value AS VARCHAR)) AS BIGINT) AS n_granos,
        CAST(count(DISTINCT CAST(codmes AS VARCHAR)) AS BIGINT) AS n_meses,
        min(CAST(codmes AS VARCHAR)) AS mes_min,
        max(CAST(codmes AS VARCHAR)) AS mes_max,
        CAST(count(target_01m) AS BIGINT) AS nn01, CAST(sum(target_01m) AS BIGINT) AS nm01, max(CASE WHEN target_01m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx01,
        CAST(count(target_02m) AS BIGINT) AS nn02, CAST(sum(target_02m) AS BIGINT) AS nm02, max(CASE WHEN target_02m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx02,
        CAST(count(target_03m) AS BIGINT) AS nn03, CAST(sum(target_03m) AS BIGINT) AS nm03, max(CASE WHEN target_03m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx03,
        CAST(count(target_04m) AS BIGINT) AS nn04, CAST(sum(target_04m) AS BIGINT) AS nm04, max(CASE WHEN target_04m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx04,
        CAST(count(target_05m) AS BIGINT) AS nn05, CAST(sum(target_05m) AS BIGINT) AS nm05, max(CASE WHEN target_05m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx05,
        CAST(count(target_06m) AS BIGINT) AS nn06, CAST(sum(target_06m) AS BIGINT) AS nm06, max(CASE WHEN target_06m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx06,
        CAST(count(target_07m) AS BIGINT) AS nn07, CAST(sum(target_07m) AS BIGINT) AS nm07, max(CASE WHEN target_07m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx07,
        CAST(count(target_08m) AS BIGINT) AS nn08, CAST(sum(target_08m) AS BIGINT) AS nm08, max(CASE WHEN target_08m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx08,
        CAST(count(target_09m) AS BIGINT) AS nn09, CAST(sum(target_09m) AS BIGINT) AS nm09, max(CASE WHEN target_09m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx09,
        CAST(count(target_10m) AS BIGINT) AS nn10, CAST(sum(target_10m) AS BIGINT) AS nm10, max(CASE WHEN target_10m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx10,
        CAST(count(target_11m) AS BIGINT) AS nn11, CAST(sum(target_11m) AS BIGINT) AS nm11, max(CASE WHEN target_11m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx11,
        CAST(count(target_12m) AS BIGINT) AS nn12, CAST(sum(target_12m) AS BIGINT) AS nm12, max(CASE WHEN target_12m IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS mx12,
        CAST(sum(CASE WHEN target_01m = 1 AND target_02m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo01,
        CAST(sum(CASE WHEN target_02m = 1 AND target_03m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo02,
        CAST(sum(CASE WHEN target_03m = 1 AND target_04m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo03,
        CAST(sum(CASE WHEN target_04m = 1 AND target_05m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo04,
        CAST(sum(CASE WHEN target_05m = 1 AND target_06m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo05,
        CAST(sum(CASE WHEN target_06m = 1 AND target_07m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo06,
        CAST(sum(CASE WHEN target_07m = 1 AND target_08m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo07,
        CAST(sum(CASE WHEN target_08m = 1 AND target_09m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo08,
        CAST(sum(CASE WHEN target_09m = 1 AND target_10m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo09,
        CAST(sum(CASE WHEN target_10m = 1 AND target_11m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo10,
        CAST(sum(CASE WHEN target_11m = 1 AND target_12m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo11,
        CAST(sum(CASE WHEN target_01m = 1 AND target_12m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS mo12,
        CAST(sum(CASE WHEN target_01m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb01,
        CAST(sum(CASE WHEN target_02m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb02,
        CAST(sum(CASE WHEN target_03m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb03,
        CAST(sum(CASE WHEN target_04m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb04,
        CAST(sum(CASE WHEN target_05m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb05,
        CAST(sum(CASE WHEN target_06m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb06,
        CAST(sum(CASE WHEN target_07m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb07,
        CAST(sum(CASE WHEN target_08m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb08,
        CAST(sum(CASE WHEN target_09m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb09,
        CAST(sum(CASE WHEN target_10m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb10,
        CAST(sum(CASE WHEN target_11m IS NULL AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS nb11,
        CAST(sum(CASE WHEN target_12m IS NULL AND falla_madurez_12m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS nb12,
        CAST(sum(falla_score_dup) AS BIGINT) AS v_scoredup,
        CAST(sum(CASE WHEN probabilidad IS NOT NULL AND COALESCE(TRY_CAST(substr(CAST(codmes AS VARCHAR), 1, 4) AS INTEGER) * 12 + TRY_CAST(substr(CAST(codmes AS VARCHAR), 5, 2) AS INTEGER) - TRY_CAST(substr(CAST(score_p_codmes AS VARCHAR), 1, 4) AS INTEGER) * 12 - TRY_CAST(substr(CAST(score_p_codmes AS VARCHAR), 5, 2) AS INTEGER), -99) <> 1 THEN 1 ELSE 0 END) AS BIGINT) AS v_desfase,
        CAST(sum(CASE WHEN probabilidad IS NOT NULL AND (TRY_CAST(probabilidad AS DOUBLE) IS NULL OR TRY_CAST(probabilidad AS DOUBLE) < 0 OR TRY_CAST(probabilidad AS DOUBLE) > 1) THEN 1 ELSE 0 END) AS BIGINT) AS v_pdrango,
        CAST(sum(falla_pd_rango) AS BIGINT) AS v_pdflag,
        CAST(sum(CASE WHEN flag_bpe_parcial IS NULL THEN 1 ELSE 0 END) AS BIGINT) AS v_sinbpe,
        CAST(sum(CASE WHEN flagcruce IS NULL THEN 1 ELSE 0 END) AS BIGINT) AS v_sincruce,
        CAST(sum(CASE WHEN ent_alta IS DISTINCT FROM cod_instit_financiera THEN 1 ELSE 0 END) AS BIGINT) AS v_entalta,
        CAST(sum(CASE WHEN nombre_instit_financiera IS NULL THEN 1 ELSE 0 END) AS BIGINT) AS v_nombre,
        CAST(sum(falla_sin_entidad_alta) AS BIGINT) AS v_sinent,
        CAST(sum(CASE WHEN falla_madurez_12m = 1 AND target_12m IS NOT NULL THEN 1 ELSE 0 END) AS BIGINT) AS v_mad1t,
        CAST(sum(CASE WHEN falla_madurez_12m = 0 AND target_12m IS NULL THEN 1 ELSE 0 END) AS BIGINT) AS v_mad0t,
        CAST(sum(CASE WHEN falla_sin_rcc_futuro = 1 AND target_12m = 1 THEN 1 ELSE 0 END) AS BIGINT) AS v_a3,
        CAST(sum(CASE WHEN saldo_vig_m0 IS NULL OR CAST(saldo_vig_m0 AS DOUBLE) <= 0 THEN 1 ELSE 0 END) AS BIGINT) AS v_svm0,
        CAST(sum(CASE WHEN flag_malo_12m IN ('SIN_INFORMACION','INSUFICIENTE') AND target_12m IS NULL AND falla_madurez_12m = 0 THEN 1 ELSE 0 END) AS BIGINT) AS v_blanda,
        CAST(sum(CASE WHEN COALESCE(falla_sin_score, -1) <> (CASE WHEN probabilidad IS NULL THEN 1 ELSE 0 END) THEN 1 ELSE 0 END) AS BIGINT) AS v_sinscore,
        CAST(count(probabilidad) AS BIGINT) AS o_conscore,
        CAST(count(DISTINCT CASE WHEN probabilidad IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS BIGINT) AS o_mesesscore,
        min(CASE WHEN probabilidad IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS o_scoremin,
        max(CASE WHEN probabilidad IS NOT NULL THEN CAST(codmes AS VARCHAR) END) AS o_scoremax,
        round(min(TRY_CAST(probabilidad AS DOUBLE)), 6) AS o_pdmin,
        round(avg(TRY_CAST(probabilidad AS DOUBLE)), 6) AS o_pdavg,
        round(max(TRY_CAST(probabilidad AS DOUBLE)), 6) AS o_pdmax
    FROM disc_model_owner.ds_adm_bpe_bankbn_mad
)
SELECT
    t.bloque,
    t.orden,
    t.item,
    t.n_viol,
    t.n_viol2,
    t.n_base,
    t.n_extra,
    round(100e0 * t.n_extra / nullif(t.n_base, 0), 5) AS tasa_o_pct,
    t.txt,
    CASE WHEN t.n_viol = 0 AND t.n_viol2 = 0 THEN 'OK' ELSE 'REVISAR' END AS veredicto,
    a.n_filas,
    a.n_meses,
    a.mes_min,
    a.mes_max,
    a.o_conscore,
    a.o_mesesscore,
    a.o_scoremin,
    a.o_scoremax,
    a.o_pdmin,
    a.o_pdavg,
    a.o_pdmax
FROM a
CROSS JOIN UNNEST(ARRAY[
    ROW('H_HORIZONTE', 1, 'target_01m', a.mo01, a.nb01, a.nn01, a.nm01, a.mx01),
    ROW('H_HORIZONTE', 2, 'target_02m', a.mo02, a.nb02, a.nn02, a.nm02, a.mx02),
    ROW('H_HORIZONTE', 3, 'target_03m', a.mo03, a.nb03, a.nn03, a.nm03, a.mx03),
    ROW('H_HORIZONTE', 4, 'target_04m', a.mo04, a.nb04, a.nn04, a.nm04, a.mx04),
    ROW('H_HORIZONTE', 5, 'target_05m', a.mo05, a.nb05, a.nn05, a.nm05, a.mx05),
    ROW('H_HORIZONTE', 6, 'target_06m', a.mo06, a.nb06, a.nn06, a.nm06, a.mx06),
    ROW('H_HORIZONTE', 7, 'target_07m', a.mo07, a.nb07, a.nn07, a.nm07, a.mx07),
    ROW('H_HORIZONTE', 8, 'target_08m', a.mo08, a.nb08, a.nn08, a.nm08, a.mx08),
    ROW('H_HORIZONTE', 9, 'target_09m', a.mo09, a.nb09, a.nn09, a.nm09, a.mx09),
    ROW('H_HORIZONTE', 10, 'target_10m', a.mo10, a.nb10, a.nn10, a.nm10, a.mx10),
    ROW('H_HORIZONTE', 11, 'target_11m', a.mo11, a.nb11, a.nn11, a.nm11, a.mx11),
    ROW('H_HORIZONTE', 12, 'target_12m', a.mo12, a.nb12, a.nn12, a.nm12, a.mx12),
    ROW('M_CHK', 21, 'M01 grano duplicado', a.n_filas - a.n_granos, CAST(0 AS BIGINT), a.n_filas, a.n_granos, '-'),
    ROW('M_CHK', 22, 'M02 falla_score_dup prendido', a.v_scoredup, CAST(0 AS BIGINT), a.n_filas, a.v_scoredup, '-'),
    ROW('M_CHK', 23, 'M03 desfase codmes vs score_p_codmes distinto de 1', a.v_desfase, CAST(0 AS BIGINT), a.o_conscore, a.v_desfase, '-'),
    ROW('M_CHK', 24, 'M04 pd fuera de 0 a 1 o no casteable', a.v_pdrango, a.v_pdflag, a.o_conscore, a.v_pdrango, '-'),
    ROW('M_CHK', 25, 'M05 flag_bpe_parcial NULL join a tmp_mad_bpe', a.v_sinbpe, a.v_sincruce, a.n_filas, a.v_sinbpe, '-'),
    ROW('M_CHK', 26, 'M06 ent_alta distinto de cod_instit_financiera', a.v_entalta, a.v_sinent, a.n_filas, a.v_entalta, '-'),
    ROW('M_CHK', 27, 'M07 nombre_instit_financiera NULL', a.v_nombre, CAST(0 AS BIGINT), a.n_filas, a.v_nombre, '-'),
    ROW('M_CHK', 28, 'M08 madurez 12m dice inmaduro pero target no es NULL', a.v_mad1t, CAST(0 AS BIGINT), a.n_filas, a.v_mad1t, '-'),
    ROW('M_CHK', 29, 'M09 madurez 12m dice maduro pero target es NULL', a.v_mad0t, CAST(0 AS BIGINT), a.n_filas, a.v_mad0t, '-'),
    ROW('M_CHK', 30, 'M10 A3 sin rcc futuro nro_miss12=12 pero target_12m=1', a.v_a3, CAST(0 AS BIGINT), a.n_filas, a.v_a3, '-'),
    ROW('M_CHK', 31, 'M11 saldo_vig_m0 nulo o no positivo', a.v_svm0, CAST(0 AS BIGINT), a.n_filas, a.v_svm0, '-'),
    ROW('M_CHK', 32, 'M12 maduracion blanda anula el target A3', a.v_blanda, CAST(0 AS BIGINT), a.n_filas, a.v_blanda, '-'),
    ROW('M_CHK', 33, 'M13 falla_sin_score no coincide con probabilidad NULL', a.v_sinscore, CAST(0 AS BIGINT), a.n_filas, a.v_sinscore, '-'),
    ROW('M_CHK', 34, 'M14 huecos de mes en la cobertura', CAST(date_diff('month', date_parse(a.mes_min, '%Y%m'), date_parse(a.mes_max, '%Y%m')) + 1 - a.n_meses AS BIGINT), CAST(0 AS BIGINT), a.n_meses, a.n_meses, '-')
]) AS t (bloque, orden, item, n_viol, n_viol2, n_base, n_extra, txt)
ORDER BY t.bloque, t.orden
